test.describe('local-time sun and moon',()=>{
  test.use({timezoneId:'Asia/Shanghai'})
  test('moves through morning/noon/evening/night and synchronizes the big screen',async({page})=>{
    const errors=[];page.on('pageerror',error=>errors.push(error.message))
    let mocked='2026-11-11T08:00:00+08:00'
    await page.clock.install({time:new Date(mocked)})
    await page.route('**/api/events',route=>route.fulfill({json:{events:[],server_time:new Date(mocked).toISOString()}}))
    await page.goto('/')
    const art=page.locator('.hero .scene-art'),body=art.locator('.scene-celestial')
    await expect(art).toHaveAttribute('data-body','sun')
    const morning={x:Number(await body.getAttribute('data-x')),y:Number(await body.getAttribute('data-y'))}
    async function changeTime(iso){mocked=iso;await page.clock.setSystemTime(new Date(iso));await page.clock.runFor(1100)}
    await changeTime('2026-11-11T12:00:00+08:00')
    await expect(art).toHaveAttribute('data-period','day')
    const noon={x:Number(await body.getAttribute('data-x')),y:Number(await body.getAttribute('data-y'))}
    expect(noon.x).toBeGreaterThan(morning.x);expect(noon.y).toBeLessThan(morning.y)
    await page.screenshot({path:'test-results/solar-noon.png',animations:'disabled'})
    await page.getByRole('button',{name:'打开沉浸大屏',exact:true}).click()
    const stage=page.getByRole('dialog',{name:'沉浸时光大屏'})
    await expect(stage.locator('.scene-art')).toHaveAttribute('data-body','sun')
    expect(await stage.locator('.scene-art').getAttribute('data-time-progress')).toBe(await art.getAttribute('data-time-progress'))
    await page.getByRole('button',{name:'关闭大屏',exact:true}).click()
    await page.getByRole('button',{name:'星河漫游',exact:true}).click()
    await expect(art).toHaveAttribute('data-body','moon')
    await page.getByRole('button',{name:'自在山野',exact:true}).click()
    await changeTime('2026-11-11T17:00:00+08:00')
    await expect(art).toHaveAttribute('data-period','dusk')
    expect(Number(await body.getAttribute('data-x'))).toBeGreaterThan(noon.x)
    expect(Number(await body.getAttribute('data-y'))).toBeGreaterThan(noon.y)
    await changeTime('2026-11-11T20:00:00+08:00')
    await expect(art).toHaveAttribute('data-body','moon')
    await expect(art).toHaveAttribute('data-period','night')
    await expect(art.locator('mask')).toHaveCount(1)
    const earlyMoon=Number(await body.getAttribute('data-x'))
    await page.screenshot({path:'test-results/solar-night.png',animations:'disabled'})
    await changeTime('2026-11-12T00:00:00+08:00')
    expect(Number(await body.getAttribute('data-x'))).toBeGreaterThan(earlyMoon)
    await page.setViewportSize({width:390,height:844})
    await page.clock.runFor(1100)
    const bounds=await art.evaluate(el=>({width:el.clientWidth,height:el.clientHeight}))
    const visible=Math.min(1200,360*bounds.width/bounds.height),left=(1200-visible)/2
    const mobileX=Number(await body.getAttribute('data-x'))
    expect(mobileX).toBeGreaterThan(left);expect(mobileX).toBeLessThan(left+visible)
    expect(errors).toEqual([])
  })
})

